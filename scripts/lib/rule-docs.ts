/**
 * Renders docs/rules/<rule-id>.md from each rule's metadata (the same text the reports
 * use), keeping two hand-written regions per page: what the rule detects, and its false
 * positives and limitations. Used by scripts/rule-docs.ts and test/unit/docs.test.ts.
 */
import type { RuleMeta } from '../../src/core/engine/rule.ts';
import { SECURITY_SEVERITY } from '../../src/reporters/sarif.ts';

export const RULE_DOCS_DIR = 'docs/rules';
export const HAND_REGIONS = ['detects', 'false-positives'] as const;
export type HandRegion = (typeof HAND_REGIONS)[number];
const PLACEHOLDER = 'TODO: hand-written section.';

/** Names for every CWE a rule cites. A new CWE without a name fails generation. */
export const CWE_NAMES: Readonly<Record<number, string>> = {
  200: 'Exposure of Sensitive Information to an Unauthorized Actor',
  259: 'Use of Hard-coded Password',
  269: 'Improper Privilege Management',
  284: 'Improper Access Control',
  285: 'Improper Authorization',
  306: 'Missing Authentication for Critical Function',
  307: 'Improper Restriction of Excessive Authentication Attempts',
  312: 'Cleartext Storage of Sensitive Information',
  321: 'Use of Hard-coded Cryptographic Key',
  345: 'Insufficient Verification of Data Authenticity',
  346: 'Origin Validation Error',
  347: 'Improper Verification of Cryptographic Signature',
  522: 'Insufficiently Protected Credentials',
  538: 'Insertion of Sensitive Information into Externally-Accessible File or Directory',
  639: 'Authorization Bypass Through User-Controlled Key',
  798: 'Use of Hard-coded Credentials',
  799: 'Improper Control of Interaction Frequency',
  862: 'Missing Authorization',
  942: 'Permissive Cross-domain Policy with Untrusted Domains',
  1188: 'Initialization of a Resource with an Insecure Default',
};

export function rulePagePath(ruleId: string): string {
  return `${RULE_DOCS_DIR}/${ruleId}.md`;
}

export function extractHandRegions(page: string): Partial<Record<HandRegion, string>> {
  const out: Partial<Record<HandRegion, string>> = {};
  for (const r of HAND_REGIONS) {
    const m = new RegExp(`<!-- hand:${r} -->\\s*\\n([\\s\\S]*?)\\n\\s*<!-- /hand:${r} -->`).exec(
      page,
    );
    if (m?.[1] !== undefined) out[r] = m[1].trim();
  }
  return out;
}

export function isPlaceholder(text: string | undefined): boolean {
  return text === undefined || text.trim() === '' || text.includes(PLACEHOLDER);
}

function fence(code: string, lang: string): string {
  const longest = Math.max(2, ...Array.from(code.matchAll(/`{3,}/g), (m) => m[0].length));
  const f = '`'.repeat(longest + 1);
  return `${f}${lang}\n${code.replace(/\n+$/, '')}\n${f}`;
}

/** Comment syntax for a suppression example, by the remediation's code language. */
function suppressionExample(m: RuleMeta): { lang: string; code: string } {
  const reason = 'explain why this is safe (at least 10 characters)';
  const lang = m.docs.remediation.codeLanguage;
  if (lang === 'sql')
    return {
      lang: 'sql',
      code: `-- vibeguard-ignore-next-line ${m.id} -- ${reason}\n<the statement VibeGuard reported>`,
    };
  if (lang === 'bash')
    return {
      lang: 'bash',
      code: `# vibeguard-ignore-file ${m.id} -- ${reason}\nNAME=value`,
    };
  return {
    lang: 'ts',
    code: `// vibeguard-ignore-next-line ${m.id} -- ${reason}\n<the line VibeGuard reported>`,
  };
}

/** "1) Do this. 2) Then that." becomes an ordered list; other text stays a paragraph. */
function remediationSteps(text: string): string[] {
  const safe = text.replace(/<([a-z]+)>/g, '`<$1>`');
  if (!/^1\) /.test(safe)) return [safe];
  return safe.split(/\s(?=\d+\) )/).map((step) => step.replace(/^(\d+)\) /, '$1. '));
}

export function renderRulePage(m: RuleMeta, hand: Partial<Record<HandRegion, string>>): string {
  const cweLink = (n: number): string =>
    `[CWE-${n}](https://cwe.mitre.org/data/definitions/${n}.html)`;
  const cwe = m.cwe.map((n) => {
    const name = CWE_NAMES[n];
    if (name === undefined) throw new Error(`CWE-${n} (${m.id}) has no entry in CWE_NAMES`);
    return `${cweLink(n)}: ${name}`;
  });
  const r = m.docs.remediation;
  const sup = suppressionExample(m);
  const region = (name: HandRegion): string =>
    [`<!-- hand:${name} -->`, '', hand[name] ?? PLACEHOLDER, '', `<!-- /hand:${name} -->`].join(
      '\n',
    );
  return [
    `# \`${m.id}\`: ${m.docs.title.en}`,
    '',
    '<!-- Generated by `npm run docs:rules` from the rule metadata in src/rules/. Edit only the',
    '     hand:* regions here; everything else comes from the rule and is overwritten. -->',
    '',
    '| Family | Default severity | GitHub security-severity | CWE |',
    '| --- | --- | --- | --- |',
    `| ${m.family} | ${m.defaultSeverity} | ${SECURITY_SEVERITY[m.defaultSeverity]} | ${m.cwe.map(cweLink).join(', ')} |`,
    '',
    'Individual findings can have a lower or higher severity than the default, and each has a',
    'confidence (high, medium or low). Both are explained below.',
    '',
    '## What it detects',
    '',
    region('detects'),
    '',
    '## Why it matters',
    '',
    m.docs.summary.en,
    '',
    '## Messages',
    '',
    'What a finding from this rule says (parameters in braces):',
    '',
    ...Object.values(m.messages).map(
      (msg) => `- ${msg.en.replace(/[<>]/g, (c) => (c === '<' ? '&lt;' : '&gt;'))}`,
    ),
    '',
    '## How to fix',
    '',
    ...remediationSteps(r.text.en),
    '',
    '### Vulnerable',
    '',
    fence(r.vulnerable, r.codeLanguage),
    '',
    '### Fixed',
    '',
    fence(r.fixed, r.codeLanguage),
    '',
    '## False positives and limitations',
    '',
    region('false-positives'),
    '',
    '## How to suppress',
    '',
    'Only suppress a finding after confirming it is safe. Put the directive on the line above',
    'the reported line (or use `vibeguard-ignore-line` on the line itself, or',
    '`vibeguard-ignore-file` anywhere in the file). The reason is required: a directive without',
    'one suppresses nothing and is reported.',
    '',
    fence(sup.code, sup.lang),
    '',
    'Use the comment syntax of the file: `//` or `/* */` in code, `#` in `.env` and YAML',
    'files, `--` in SQL.',
    '',
    'To turn the rule off or change its severity for the whole project, use `.vibeguard.yml`:',
    '',
    fence(`version: 1\nrules:\n  ${m.id}: off # or: { severity: low }`, 'yaml'),
    '',
    'See [configuration](../../configuration.md) and',
    '[ADR-0004](../../adr/0004-suppression-design.md).',
    '',
    '## CWE',
    '',
    ...cwe.map((c) => `- ${c}`),
    '',
    '## References',
    '',
    ...m.references.map((u) => `- <${u}>`),
    '',
  ].join('\n');
}

export function renderIndex(metas: readonly RuleMeta[]): string {
  return [
    '# Rules',
    '',
    '<!-- Generated by `npm run docs:rules`. Do not edit by hand. -->',
    '',
    'VibeGuard v1 has exactly three rule families. Every finding links to its rule page.',
    '',
    '| Rule | Default severity | What it finds |',
    '| --- | --- | --- |',
    ...metas.map(
      (m) => `| [\`${m.id}\`](${m.id}.md) | ${m.defaultSeverity} | ${m.docs.title.en} |`,
    ),
    '',
  ].join('\n');
}
