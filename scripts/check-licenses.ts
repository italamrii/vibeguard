/**
 * Dependency license gate and inventory (reads package-lock.json only; no network).
 *
 *   npm run licenses:check            # regenerate docs/dependencies.md
 *   npm run licenses:check -- --check # CI: fail on a disallowed license or a stale doc
 *
 * Policy (VibeGuard is Apache-2.0):
 *  - Runtime dependencies (installed for users with the package) must be permissive and
 *    Apache-2.0-compatible: MIT, ISC, Apache-2.0, BSD-2-Clause, BSD-3-Clause, 0BSD,
 *    BlueOak-1.0.0.
 *  - Dev-only dependencies are never redistributed, so file-level weak copyleft (MPL-2.0)
 *    is also accepted there. Strong copyleft (GPL, AGPL, LGPL, SSPL), unknown and missing
 *    licenses fail everywhere.
 * SPDX expressions: `A OR B` passes if either side does; `A AND B` only if both do.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { parseArgs } from 'node:util';
import { format, resolveConfig } from 'prettier';

const RUNTIME_ALLOWED = new Set([
  'MIT',
  'ISC',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'BlueOak-1.0.0',
]);
const DEV_ALLOWED = new Set([...RUNTIME_ALLOWED, 'MPL-2.0']);
const DOC = 'docs/dependencies.md';

interface LockEntry {
  version?: string;
  license?: unknown;
  dev?: boolean;
  devOptional?: boolean;
  optional?: boolean;
}

/** Evaluate a (simple) SPDX expression against an allowlist. */
function licenseAllowed(expr: string, allowed: ReadonlySet<string>): boolean {
  const e = expr.trim().replace(/^\((.*)\)$/, '$1');
  if (/\sOR\s/.test(e)) return e.split(/\s+OR\s+/).some((p) => licenseAllowed(p, allowed));
  if (/\sAND\s/.test(e)) return e.split(/\s+AND\s+/).every((p) => licenseAllowed(p, allowed));
  return allowed.has(e);
}

const { values } = parseArgs({ options: { check: { type: 'boolean', default: false } } });
const lock = JSON.parse(await readFile('package-lock.json', 'utf8')) as {
  packages: Record<string, LockEntry>;
};
const pkg = JSON.parse(await readFile('package.json', 'utf8')) as {
  dependencies?: Record<string, string>;
};
const direct = new Set(Object.keys(pkg.dependencies ?? {}));

interface Dep {
  name: string;
  version: string;
  license: string;
  runtime: boolean;
}
const deps: Dep[] = [];
for (const [key, v] of Object.entries(lock.packages)) {
  if (key === '') continue;
  const name = key.slice(key.lastIndexOf('node_modules/') + 'node_modules/'.length);
  const license = typeof v.license === 'string' ? v.license : 'UNKNOWN';
  deps.push({
    name,
    version: v.version ?? '?',
    license,
    runtime: v.dev !== true && v.devOptional !== true,
  });
}
deps.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const problems: string[] = [];
for (const d of deps) {
  const ok = licenseAllowed(d.license, d.runtime ? RUNTIME_ALLOWED : DEV_ALLOWED);
  if (!ok) problems.push(`${d.runtime ? 'runtime' : 'dev'} ${d.name}@${d.version}: ${d.license}`);
}

const runtime = deps.filter((d) => d.runtime);
const dev = deps.filter((d) => !d.runtime);
const byLicense = new Map<string, number>();
for (const d of dev) byLicense.set(d.license, (byLicense.get(d.license) ?? 0) + 1);

const doc = [
  '# Dependencies and licenses',
  '',
  'Generated by `npm run licenses:check` from `package-lock.json`. Do not edit by hand.',
  'CI fails if this file is stale or if any dependency has a license outside the policy',
  'in [`scripts/check-licenses.ts`](../scripts/check-licenses.ts).',
  '',
  '## Runtime dependencies',
  '',
  'Installed for users together with `@italamrii/vibeguard` (direct and transitive). All',
  'must be permissive and compatible with Apache-2.0.',
  '',
  '| Package | Version | License | Direct |',
  '| --- | --- | --- | --- |',
  ...runtime.map(
    (d) => `| \`${d.name}\` | ${d.version} | ${d.license} | ${direct.has(d.name) ? 'yes' : 'no'} |`,
  ),
  '',
  '## Development dependencies',
  '',
  `${dev.length} packages, used only to build, lint and test VibeGuard. They are not part of`,
  'the published package. MPL-2.0 (file-level copyleft) is accepted here because these',
  'packages are never redistributed.',
  '',
  '| License | Packages |',
  '| --- | ---: |',
  ...[...byLicense]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([l, n]) => `| ${l} | ${n} |`),
  '',
  'Non-MIT development dependencies:',
  '',
  ...dev
    .filter((d) => d.license !== 'MIT')
    .map((d) => `- \`${d.name}\` ${d.version}: ${d.license}`),
  '',
].join('\n');
const formatted = await format(doc, {
  ...(await resolveConfig(DOC)),
  parser: 'markdown',
  filepath: DOC,
});

if (values.check) {
  const current = await readFile(DOC, 'utf8').catch(() => '');
  if (current !== formatted) problems.push(`${DOC} is stale: run npm run licenses:check`);
} else {
  await writeFile(DOC, formatted);
}

console.log(
  `licenses: ${runtime.length} runtime and ${dev.length} dev packages checked, ${problems.length} problem(s)`,
);
for (const p of problems) console.error(`  - ${p}`);
if (problems.length > 0) process.exitCode = 1;
