/**
 * Measure precision and recall of every rule against the fixture apps and write
 * docs/accuracy.md.  `npm run accuracy` (add `-- --check` to fail on any FP/FN instead
 * of only reporting).
 */
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { format } from 'prettier';
import { resolveSettings } from '../src/core/config/settings.ts';
import { scan } from '../src/core/engine/engine.ts';
import { ALL_RULES } from '../src/rules/index.ts';
import {
  compare,
  precision,
  readExpectations,
  recall,
  type RuleScore,
} from '../test/helpers/accuracy.ts';
import { buildFixtures, FIXTURES_DIR } from '../test/helpers/fixtures.ts';

const { values } = parseArgs({ options: { check: { type: 'boolean', default: false } } });
const pct = (n: number): string => `${(n * 100).toFixed(1)}%`;

const out = await mkdtemp(path.join(tmpdir(), 'vg-accuracy-'));
try {
  const built = await buildFixtures(out);
  const totals = new Map<string, RuleScore>();
  const appRows: string[] = [];
  const problems: string[] = [];
  for (const app of built.apps) {
    const dir = path.join(out, app);
    const r = await scan({ root: dir, settings: resolveSettings(undefined), rules: ALL_RULES });
    const c = compare(await readExpectations(dir), r.findings);
    let tp = 0;
    let fp = 0;
    let fn = 0;
    for (const [rule, s] of c.byRule) {
      const t = totals.get(rule) ?? { tp: 0, fp: 0, fn: 0, knownMisses: 0 };
      t.tp += s.tp;
      t.fp += s.fp;
      t.fn += s.fn;
      t.knownMisses += s.knownMisses;
      totals.set(rule, t);
      tp += s.tp;
      fp += s.fp;
      fn += s.fn;
    }
    const active = r.findings.filter((f) => !f.suppression).length;
    const suppressed = r.findings.length - active;
    appRows.push(
      `| \`${app}\` | ${active} | ${suppressed} | ${tp} | ${fp} | ${fn} | ${r.complete ? 'yes' : '**no**'} |`,
    );
    for (const f of c.falsePositives)
      problems.push(`FP ${app}: ${f.ruleId} ${f.location.file}:${f.location.line}`);
    for (const e of c.falseNegatives) problems.push(`FN ${app}: ${e.ruleId} ${e.file}:${e.line}`);
  }

  const ruleIds = ALL_RULES.map((r) => r.meta.id);
  const all: RuleScore = { tp: 0, fp: 0, fn: 0, knownMisses: 0 };
  const ruleRows = ruleIds.map((id) => {
    const s = totals.get(id) ?? { tp: 0, fp: 0, fn: 0, knownMisses: 0 };
    all.tp += s.tp;
    all.fp += s.fp;
    all.fn += s.fn;
    all.knownMisses += s.knownMisses;
    return `| \`${id}\` | ${s.tp} | ${s.fp} | ${s.fn} | ${s.knownMisses} | ${pct(precision(s))} | ${pct(recall(s))} |`;
  });

  const md = `# Detection accuracy on the fixture apps

Generated by \`npm run accuracy\` from the templates in [\`fixtures/\`](../fixtures). Do not edit by hand.

Each vulnerable app annotates every expected finding (\`vg-expect: <rule>\`), and known
false negatives (\`vg-expect-miss\`). Each clean app must produce **zero** findings. A finding
counts as a true positive only if rule, file **and line** match an annotation.

**These numbers measure VibeGuard against fixtures its authors wrote.** They show the rules
behave as designed and catch regressions. They are not an estimate of real-world precision
or recall. See [threat-model.md](threat-model.md) for what the rules cannot detect.

## Per rule

| Rule | TP | FP | FN | of which known misses | Precision | Recall |
| ---- | -: | -: | -: | -: | -: | -: |
${ruleRows.join('\n')}
| **All rules** | **${all.tp}** | **${all.fp}** | **${all.fn}** | **${all.knownMisses}** | **${pct(precision(all))}** | **${pct(recall(all))}** |

## Per app

| App | Findings | Suppressed (with reason) | TP | FP | FN | Scan complete |
| --- | -: | -: | -: | -: | -: | --- |
${appRows.join('\n')}

## Known misses

Declared with \`vg-expect-miss\` in the fixtures:

- \`secrets/provider-key\`: a key assembled by string concatenation (\`'sk' + '_live_' + body\`)
  is not reassembled. Detection is per literal.
- \`supabase/rls-disabled\`: RLS disabled from inside a PL/pgSQL \`DO\` block. Blocks are not
  executed. The table is marked unknown and a \`dynamic-sql\` notice makes the report state
  that coverage is partial, but no finding is raised for the table itself.

The clean apps contain one suppressed finding by design: a read-only \`USING (true)\` policy on
\`public.countries\` (public reference data), reported at low severity / low confidence and
suppressed in the fixture with a reason, which is the intended workflow for deliberate exceptions.
`;
  const target = path.join(path.dirname(FIXTURES_DIR), 'docs', 'accuracy.md');
  const md2 =
    md +
    (await realWorldSection(
      path.join(path.dirname(FIXTURES_DIR), 'docs', 'real-world-validation.json'),
    ));
  // Format like the rest of the repo so regenerating never breaks `prettier --check`.
  const formatted = await format(md2, { parser: 'markdown', filepath: target });
  await writeFile(target, formatted);
  console.log(formatted);
  if (problems.length > 0) {
    console.error(problems.join('\n'));
    if (values.check) process.exitCode = 1;
  }
} finally {
  await rm(out, { recursive: true, force: true });
}

interface Count {
  ruleId: string;
  count: number;
  pattern?: string;
  severity?: string;
  confidence?: string;
  status?: string;
}
interface RealWorld {
  projects: {
    id: string;
    scanned: string;
    stack: string;
    filesScanned: number;
    openFindings: Count[];
    falsePositivesFixed: Count[];
    falseNegativesFixed: Count[];
  }[];
}

/** "Real-world validation": counts only, from docs/real-world-validation.json. */
async function realWorldSection(file: string): Promise<string> {
  const { readFile } = await import('node:fs/promises');
  const data = JSON.parse(await readFile(file, 'utf8')) as RealWorld;
  const sum = (xs: Count[]): number => xs.reduce((n, x) => n + x.count, 0);
  const rows = (xs: Count[], extra: (x: Count) => string): string =>
    xs.length === 0
      ? '_none_\n'
      : xs
          .map((x) => `| ${x.ruleId === '' ? '' : `\`${x.ruleId}\``} | ${x.count} | ${extra(x)} |`)
          .join('\n') + '\n';
  const fps = data.projects.flatMap((p) => p.falsePositivesFixed);
  const fns = data.projects.flatMap((p) => p.falseNegativesFixed);
  const open = data.projects.flatMap((p) => p.openFindings);
  let out = `
## Real-world validation

Scans of real projects, with the owner's permission, read-only. **Counts only**: no project names,
paths, code or evidence are recorded. Every false positive found is fixed generically (never
tuned to one project) with a fixture written *before* the fix; see the commit history.

- Projects scanned: **${data.projects.length}** (${data.projects.map((p) => `${p.id}: ${p.filesScanned} files, ${p.stack}`).join('; ')})
- False positives found and fixed: **${sum(fps)}** across ${new Set(fps.map((x) => x.ruleId)).size} rule(s)
- Recall gaps fixed: **${sum(fns)}** endpoints whose data access was not recognised (most were authenticated, so this is not ${sum(fns)} missed findings)
- Findings currently open (after fixes): **${sum(open)}**

### Findings after fixes, per rule

| Rule | Count | Severity / confidence, status |
| ---- | ----: | ----------------------------- |
${rows(open, (x) => `${x.severity ?? ''} / ${x.confidence ?? ''}, ${x.status ?? ''}`)}
### False positives found and fixed

| Rule | Count | Generic pattern |
| ---- | ----: | --------------- |
${rows(fps, (x) => x.pattern ?? '')}
### Recall gaps found and fixed

| Rule | Endpoints affected | Generic pattern |
| ---- | ----: | --------------- |
${rows(fns, (x) => x.pattern ?? '')}
`;
  return out;
}
