import { isolateTemplate, LRI, PDI } from '../../src/i18n/bidi.ts';
import { UI } from '../../src/i18n/ui.ts';
import { ALL_RULES } from '../../src/rules/index.ts';

/**
 * Builds docs/arabic-review.md: every Arabic string VibeGuard can print, next to its English
 * source, keyed so a reviewer can point at it. Strings live with their rules (ADR-0003) so the
 * compiler can enforce completeness; this table is the single place to proofread them.
 */
export interface ReviewEntry {
  readonly key: string;
  readonly en: string;
  readonly ar: string;
}

function walk(prefix: string, en: unknown, ar: unknown, out: ReviewEntry[]): void {
  if (typeof en === 'string' && typeof ar === 'string') {
    out.push({ key: prefix, en, ar });
    return;
  }
  if (en && typeof en === 'object' && ar && typeof ar === 'object') {
    for (const k of Object.keys(en)) {
      walk(
        prefix ? `${prefix}.${k}` : k,
        (en as Record<string, unknown>)[k],
        (ar as Record<string, unknown>)[k],
        out,
      );
    }
  }
}

export function reviewEntries(): { section: string; entries: ReviewEntry[] }[] {
  const ui: ReviewEntry[] = [];
  walk('ui', UI.en, UI.ar, ui);
  const sections = [{ section: 'Report, CLI and diagnostics (`src/i18n/ui.ts`)', entries: ui }];
  for (const rule of ALL_RULES) {
    const m = rule.meta;
    const entries: ReviewEntry[] = [
      { key: 'title', en: m.docs.title.en, ar: m.docs.title.ar },
      { key: 'summary', en: m.docs.summary.en, ar: m.docs.summary.ar },
      { key: 'remediation', en: m.docs.remediation.text.en, ar: m.docs.remediation.text.ar },
      ...Object.entries(m.messages).map(([id, t]) => ({
        key: `message.${id}`,
        en: (t as { en: string }).en,
        ar: (t as { ar: string }).ar,
      })),
    ];
    sections.push({ section: `Rule \`${m.id}\``, entries });
  }
  return sections;
}

function cell(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>');
}

function arabicCell(s: string): string {
  // Same isolation the reports use, plus visible-but-isolated placeholders.
  return cell(isolateTemplate(s).replace(/\{[a-zA-Z0-9_]+\}/g, (p) => `${LRI}${p}${PDI}`));
}

export function renderArabicReview(): string {
  const sections = reviewEntries();
  const total = sections.reduce((n, s) => n + s.entries.length, 0);
  const out = [
    '# Arabic strings for review',
    '',
    'Generated by `npm run arabic-review` from the rule registry and `src/i18n/ui.ts`. Do not edit',
    'by hand: fix a string at its source (the rule file or `ui.ts`) and regenerate. A test fails',
    'when this file is out of date.',
    '',
    `**${total} strings** in ${sections.length} sections. \`{name}\` placeholders are filled at`,
    'runtime; code, paths and identifiers are shown isolated exactly as reports render them.',
    '',
    'Review notes: write comments against the **Key** (e.g. `secrets/provider-key › summary`).',
    '',
  ];
  for (const s of sections) {
    out.push(`## ${s.section}`, '', '| Key | English | العربية |', '| --- | --- | --- |');
    for (const e of s.entries) out.push(`| \`${e.key}\` | ${cell(e.en)} | ${arabicCell(e.ar)} |`);
    out.push('');
  }
  return out.join('\n');
}
